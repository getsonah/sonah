// D120 (owner 2026-10-18, DF3 part 1): a row the recorder chains between its own local-command caveat and that command's
// typed output is a command the person ran in the harness itself (Claude Code's /model, /clear, /compact, ...), labelled
// harness, never the person's ask — by the recorder's structure only (its uuid chain, its `isMeta` flag, its caveat
// element and the output row's typed subtype), never by a command's name. A prompt command the person sent the agent and
// a queued message stay the person's.
//
// Every fixture here is synthetic. No real recording is read.

import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { sliceLineage } from '../index.js';
import { labelClaudeRows } from '../src/records.js';
import { LABEL_BASIS, MARKERS } from '../src/labels.js';
import { isLocalCommandCaveat, RECORDER_LOCAL_COMMAND_CAVEAT, LOCAL_COMMAND_OUTPUT_SUBTYPE }
  from '../src/harness-context.js';

const base = { sessionId: 'sess-d120', cwd: '/repo', version: '2.1.295', gitBranch: 'main', isSidechain: false,
  userType: 'external', entrypoint: 'cli' };
let n = 0;
/** A chain of rows, each hanging from the one before it (the recorder's `parentUuid`), unless a row names its own. */
function chain(...specs) {
  let parent = null;
  return specs.map((spec) => {
    const uuid = `d120-${String(++n).padStart(4, '0')}`;
    const row = { ...base, parentUuid: parent, uuid, timestamp: `2026-10-18T10:00:${String(n % 60).padStart(2, '0')}.000Z`,
      ...spec };
    parent = uuid;
    return row;
  });
}
const caveat = () => ({ type: 'user', isMeta: true, message: { role: 'user', content:
  `<${RECORDER_LOCAL_COMMAND_CAVEAT}>Caveat: The messages below were generated by the user while running local commands. `
  + `DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.`
  + `</${RECORDER_LOCAL_COMMAND_CAVEAT}>` } });
const commandText = (name, args = '') => `<command-name>/${name}</command-name>\n<command-message>${name}</command-message>\n`
  + `<command-args>${args}</command-args>`;
const command = (name, extra = { origin: { kind: 'human' } }) => ({ type: 'user', message: { role: 'user',
  content: commandText(name) }, ...extra });
const output = (name) => ({ type: 'system', subtype: LOCAL_COMMAND_OUTPUT_SUBTYPE, level: 'info', isMeta: false,
  content: '<local-command-stdout>done</local-command-stdout>', commandRun: { command: name, args: '' } });
const ask = (text) => ({ type: 'user', origin: { kind: 'human' }, message: { role: 'user', content: text } });
const said = (text) => ({ type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text }] } });

const labelsOf = (rows) => labelClaudeRows(rows).map((rec) => [rec.label, rec.basis, rec.markers ?? null, rec.gap ?? null]);

async function slice(rows) {
  const dir = await mkdtemp(join(tmpdir(), 'slicer-d120-'));
  try {
    const file = join(dir, 'session.jsonl');
    await writeFile(file, rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
    return await sliceLineage([file]);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

test('D120: the caveat is read by its structure: an isMeta row that is only the recorder\'s caveat element', () => {
  assert.equal(isLocalCommandCaveat(caveat().message.content), true);
  assert.equal(isLocalCommandCaveat(`  ${caveat().message.content}\n`), true);
  // Anything else beside or around it, another element, or none: not the caveat.
  assert.equal(isLocalCommandCaveat(`${caveat().message.content} and fix the parser`), false);
  assert.equal(isLocalCommandCaveat(`${caveat().message.content}<command-name>/x</command-name>`), false);
  assert.equal(isLocalCommandCaveat('<local-command-stdout>x</local-command-stdout>'), false);
  assert.equal(isLocalCommandCaveat('Caveat: the messages below'), false);
  assert.equal(isLocalCommandCaveat(undefined), false);
});

test('D120: a row between the recorder\'s caveat and the command\'s typed output is harness, whatever its origin says', () => {
  const rows = chain(ask('Fix the parser.'), said('Fixed.'), caveat(), command('agents-info'), output('agents-info'),
    ask('Now ship it.'));
  assert.deepEqual(labelsOf(rows), [
    ['human', LABEL_BASIS.originHuman, null, null],
    ['thought', LABEL_BASIS.assistantText, null, null],
    ['harness', LABEL_BASIS.recorderMeta, null, null],
    // Typed `origin: human` by Claude Code 2.1.295, yet chained between the caveat and its output: a local command.
    ['harness', LABEL_BASIS.localCommand, null, null],
    ['harness', LABEL_BASIS.systemRow, null, null],
    ['human', LABEL_BASIS.originHuman, null, null],
  ]);
  // The same local command recorded with no origin keeps the label it always had (only a human label is settled).
  const untyped = chain(caveat(), command('model', {}), output('model'));
  assert.deepEqual(labelsOf(untyped)[1], ['harness', LABEL_BASIS.untypedElements, null, null]);
});

test('D120: both ends are needed, chained by the recorder: one end alone, or a broken chain, keeps the person\'s label', () => {
  const human = ['human', LABEL_BASIS.originHuman, [MARKERS.command], null];
  // A caveat and no output after the command (the recording ends, or the recorder wrote none).
  assert.deepEqual(labelsOf(chain(caveat(), command('agents-info')))[1], human);
  // An output and no caveat before the command.
  assert.deepEqual(labelsOf(chain(said('Done.'), command('agents-info'), output('agents-info')))[1], human);
  // The caveat is the recorder's own only when it flags it isMeta: a person who typed the element is not one.
  const typed = { type: 'user', origin: { kind: 'human' }, message: caveat().message };
  assert.deepEqual(labelsOf(chain(typed, command('agents-info'), output('agents-info')))[1], human);
  // The output names another row as its parent: the command is not between the two.
  const rows = chain(caveat(), command('agents-info'), said('Noted.'));
  rows.push({ ...chain(output('agents-info'))[0], parentUuid: rows[2].uuid });
  assert.deepEqual(labelsOf(rows)[1], human);
  // Another row between the caveat and the command breaks the chain: the command does not hang from the caveat.
  assert.deepEqual(labelsOf(chain(caveat(), said('Hm.'), command('agents-info'), output('agents-info')))[2], human);
});

test('D120: a prompt command the person sent the agent, and a queued message, stay the person\'s', () => {
  // A prompt command: no caveat before it, its expansion (isMeta prose) after it.
  const review = chain(command('review'), { type: 'user', isMeta: true, message: { role: 'user',
    content: 'Review the parser carefully.' } }, said('Reviewing.'));
  assert.deepEqual(labelsOf(review)[0], ['human', LABEL_BASIS.originHuman, [MARKERS.command], null]);
  // A local command between a prompt command and a queued message changes neither of them.
  const rows = chain(command('review'), said('Reviewing.'), caveat(), command('model'), output('model'));
  const enqueued = { ...base, type: 'queue-operation', operation: 'enqueue', content: 'Also keep the CLI flags.',
    timestamp: '2026-10-18T10:01:00.000Z' };
  const working = { ...chain(said('Still reviewing.'))[0], timestamp: '2026-10-18T10:01:01.000Z' };
  const queued = { ...chain(ask('Also keep the CLI flags.'))[0], timestamp: '2026-10-18T10:01:02.000Z' };
  const labels = labelClaudeRows([...rows, enqueued, working, queued]);
  assert.deepEqual([labels[0].label, labels[0].markers], ['human', [MARKERS.command]]);
  assert.deepEqual([labels[3].label, labels[3].basis], ['harness', LABEL_BASIS.localCommand]);
  assert.deepEqual([labels[7].label, labels[7].markers], ['human', [MARKERS.queued]]);
});

test('D120: sliced end to end, a local command is no ask and is counted as harness; the asks around it stay', async () => {
  const rows = chain(ask('Fix the parser.'), said('Fixed.'), caveat(), command('agents-info'), output('agents-info'),
    ask('Now ship it.'), said('Shipped.'));
  const ledger = await slice(rows);
  assert.deepEqual(ledger.ask.map((entry) => entry.text), ['Fix the parser.', 'Now ship it.']);
  assert.equal(ledger.capture.labels.human, 2);
  // Before D120 the command was an ask of its own: '/agents-info'.
  const before = await slice(rows.filter((row) => row.type !== 'system'));
  assert.deepEqual(before.ask.map((entry) => entry.text), ['Fix the parser.', '/agents-info', 'Now ship it.']);
});
